-- DO NOT expose this database to browsers. No payment credentials or bank PII here.
CREATE SCHEMA IF NOT EXISTS bitso_business;

CREATE TABLE IF NOT EXISTS bitso_business.webhook_inbox (
  id TEXT PRIMARY KEY CHECK (length(id) BETWEEN 20 AND 512),
  provider TEXT NOT NULL CHECK (provider = 'bitso'),
  account_id TEXT NOT NULL CHECK (length(account_id) BETWEEN 1 AND 120),
  event_type TEXT NOT NULL CHECK (event_type IN ('funding','withdrawal')),
  provider_id TEXT NOT NULL CHECK (length(provider_id) BETWEEN 1 AND 128),
  provider_status TEXT NOT NULL CHECK (provider_status IN ('pending','processing','complete','failed')),
  payload_sha256 CHAR(64) NOT NULL CHECK (payload_sha256 ~ '^[a-f0-9]{64}$'),
  received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  processing_state TEXT NOT NULL DEFAULT 'reconciliation_required'
    CHECK (processing_state IN ('reconciliation_required','reviewed','dead_letter'))
);
CREATE INDEX IF NOT EXISTS bitso_inbox_resource
 ON bitso_business.webhook_inbox (account_id,event_type,provider_id,received_at DESC);

CREATE TABLE IF NOT EXISTS bitso_business.reconciliation_outbox (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  inbox_id TEXT NOT NULL UNIQUE REFERENCES bitso_business.webhook_inbox(id),
  account_id TEXT NOT NULL,
  provider_id TEXT NOT NULL,
  event_type TEXT NOT NULL CHECK (event_type IN ('funding','withdrawal')),
  job_kind TEXT NOT NULL CHECK (job_kind='bitso-provider-reconcile'),
  state TEXT NOT NULL DEFAULT 'pending'
    CHECK (state IN ('pending','processing','done','dead_letter')),
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  claimed_at TIMESTAMPTZ,
  lease_until TIMESTAMPTZ,
  last_error_code TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS bitso_outbox_pending
 ON bitso_business.reconciliation_outbox (available_at,id)
 WHERE state='pending';
CREATE INDEX IF NOT EXISTS bitso_outbox_lease
 ON bitso_business.reconciliation_outbox (lease_until,id)
 WHERE state='processing';

CREATE TABLE IF NOT EXISTS bitso_business.reconciliation_observations (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL REFERENCES bitso_business.reconciliation_outbox(id),
 account_id TEXT NOT NULL,
 provider_id TEXT NOT NULL,
 source TEXT NOT NULL CHECK (source='authenticated-provider-query'),
 provider_status TEXT NOT NULL CHECK (provider_status IN ('pending','processing','complete','failed','not_found')),
 observed_currency TEXT,
 observed_amount TEXT,
 origin_id TEXT,
 observed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS bitso_observations_job
 ON bitso_business.reconciliation_observations(job_id,observed_at DESC);

-- Unique monotonic nonce per provider API key scope. Generated by atomic UPDATE.
CREATE TABLE IF NOT EXISTS bitso_business.readonly_nonces (
 key_scope TEXT PRIMARY KEY,
 last_nonce NUMERIC(30,0) NOT NULL CHECK (last_nonce >= 0)
);

-- The business registry remains 'candidate'; nothing here authorizes FX/payouts.


-- Prepared mapping for an independently authorized bank payout.
-- This is NOT writable from a webhook, client, or user-submitted lookup.
CREATE TABLE IF NOT EXISTS bitso_business.approved_intent_links (
  account_id TEXT NOT NULL,
  origin_id TEXT NOT NULL,
  withdrawal_id TEXT NOT NULL,
  payment_intent_id TEXT NOT NULL,
  consent_sha256 CHAR(64) NOT NULL CHECK (consent_sha256 ~ '^[a-f0-9]{64}$'),
  approval_reference TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (account_id,withdrawal_id),
  UNIQUE (account_id,origin_id),
  UNIQUE (account_id,payment_intent_id),
  CHECK (length(origin_id) BETWEEN 1 AND 40)
);
